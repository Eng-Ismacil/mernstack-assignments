const dict = { so: { ...base.so, ...extra.so }, en: { ...base.en, ...extra.en } }

const I18n = createContext(null)
export const useI18n = () => useContext(I18n)

function initial() {
  try {
    const s = localStorage.getItem('karti_lang')
    if (s === 'so' || s === 'en') return s
  } catch {}
  return (navigator.language || '').startsWith('so') ? 'so' : 'en'
}

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(initial)
  useEffect(() => {
    document.documentElement.lang = lang
    try { localStorage.setItem('karti_lang', lang) } catch {}
  }, [lang])
  const t = (k) => dict[lang][k] ?? dict.en[k] ?? k
  // Translate a Supabase auth error by its code; fall back to a generic message.
  const authError = (err) => {
    const key = 'err.' + (err?.code || '')
    return dict[lang][key] ? dict[lang][key] : (err?.message && !err?.code ? err.message : t('err.generic'))
  }
  return <I18n.Provider value={{ lang, setLang, t, authError }}>{children}</I18n.Provider>
}
